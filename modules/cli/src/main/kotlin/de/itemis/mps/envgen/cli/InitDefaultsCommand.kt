package de.itemis.mps.envgen.cli

import com.github.ajalt.clikt.core.Context
import com.github.ajalt.clikt.core.CoreCliktCommand
import com.github.ajalt.clikt.output.HelpFormatter
import com.github.ajalt.clikt.parameters.options.OptionWithValues
import com.github.ajalt.clikt.parameters.options.flag
import com.github.ajalt.clikt.parameters.options.option
import com.github.ajalt.clikt.sources.ValueSource
import java.io.File
import java.nio.file.Files
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

/** property key of an option in the defaults file: its long name without dashes, e.g. `xmx` */
internal val DEFAULTS_KEY = ValueSource.getKey()

class InitDefaultsCommand(private val services: CliServices) : CoreCliktCommand("init-defaults") {

    override fun help(context: Context) =
        "Write a template of the defaults file for 'create', listing every option commented out with its default."

    override fun helpEpilog(context: Context) = """
        Examples:
          mps-env-gen init-defaults                    write ${services.defaultsFile()}
          mps-env-gen init-defaults --print | diff - ${services.defaultsFile()}
    """.trimIndent()

    private val print by option("--print", help = "print the template instead of writing the defaults file").flag()
    private val force by option("--force", help = "replace an existing defaults file; it is backed up next to it first").flag()

    override fun run() {
        val text = defaultsTemplate(services, currentContext)
        if (print) {
            echo(text, trailingNewline = false)
            return
        }
        val file = services.defaultsFile().absoluteFile
        if (file.exists()) {
            if (!force) throw failure("$file exists already; use --force to replace it (it is backed up first) or --print to compare")
            val backup = File(file.parentFile, "${file.name}.${LocalDateTime.now().format(BACKUP_TIMESTAMP)}.bak")
            Files.copy(file.toPath(), backup.toPath())
            echo("Backed up $file to $backup")
        }
        file.parentFile.mkdirs()
        file.writeText(text)
        echo("Wrote $file")
    }

    private companion object {
        val BACKUP_TIMESTAMP: DateTimeFormatter = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss")
    }
}

/** options of `create` that describe a single invocation, not a default */
private val PER_INVOCATION_KEYS = setOf("help", "name", "temp", "start", "start-debug")

/** all options of `create`, commented out, grouped like in the help; built from the options so it cannot drift */
internal fun defaultsTemplate(services: CliServices, context: Context): String {
    val options = CreateCommand(services).registeredOptions()
        .mapNotNull { option -> option.parameterHelp(context)?.let { Triple(DEFAULTS_KEY(context, option), option, it) } }
        .filter { (key) -> key !in PER_INVOCATION_KEYS }

    return buildString {
        appendLine("# Defaults for 'mps-env-gen create', generated by mps-env-gen ${CliVersion.value}.")
        appendLine("# Keys are the long option names without '--'. Uncomment a line to set a default;")
        appendLine("# command line options and environment variables take precedence.")
        appendLine("# Repeatable options accept a single value here.")
        options.groupBy { (_, _, help) -> help.groupName ?: "General" }.forEach { (group, entries) ->
            appendLine()
            appendLine("# --- $group ---")
            entries.forEach { (key, option, help) ->
                val choices = help.metavar?.takeIf { '|' in it }?.trim('[', ']', '(', ')', '<', '>')
                val envvar = (option as? OptionWithValues<*, *, *>)?.envvar
                val details = listOfNotNull(choices?.let { "values: $it" }, envvar?.let { "environment: $it" })
                appendLine("# ${help.help}${details.joinToString("") { "; $it" }}")
                appendLine("#$key=${exampleValue(help)}")
            }
        }
    }
}

/** the default if there is one; flags show the value that changes their default */
private fun exampleValue(help: HelpFormatter.ParameterHelp.Option): String {
    val default = help.tags[HelpFormatter.Tags.DEFAULT]?.takeIf { it.isNotEmpty() }
    return when {
        help.nvalues.last == 0 -> (default != "true").toString()
        else -> default ?: ""
    }
}
